// Boss templates for the Boss Battle game mode.
// 30 thematic bosses covering 6 elements. Each boss is a "template" with
// base stats at level 1. The bossScaling lib scales them exponentially
// to any level 1-300 (open world — user picks any level).
//
// Difficulty curve: stat = base * 1.05^level
//   Level 1:  ~1.05x base
//   Level 50: ~11.5x base
//   Level 100: ~131x base
//   Level 200: ~17,292x base
//   Level 300: ~2,272,000x base

export type BossElement = 'FIRE' | 'WATER' | 'GRASS' | 'ELECTRIC' | 'PSYCHIC' | 'NORMAL';

